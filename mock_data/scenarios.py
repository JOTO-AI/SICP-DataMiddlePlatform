"""Small scenario inputs and explicit oracles; never call a production merge/query."""

from copy import deepcopy

from .source import (TABLES, CAMPUS, ORG, STAFF, STAFF_CONTACT, STUDENT, CONTACT,
    STATUS, MAJOR, GRADE_MAJOR, CLASS, COURSE, GRADE, SCHEDULE, MEMBER,
    Number, write)

OLD = "2026-08-05 07:50:00"
NEW = "2026-08-05 09:00:00"


def envelope(rows, total=None):
    return {"code": 200, "message": "请求成功", "data": {"list": rows, "total": len(rows) if total is None else total}}


def generate_scenarios(root, baseline, catalog, *, writer=write):
    index = []

    def save(group, name, inputs, expected, basis, note=""):
        folder = f"{group}/{name}"
        writer(root / folder / "input.json", inputs)
        writer(root / folder / "expected.json", expected)
        meta = {"id": name, "group": group, "basis": basis, "note": note,
            "input": folder + "/input.json", "expected": folder + "/expected.json"}
        writer(root / folder / "case.json", meta)
        index.append(meta)

    # These rows and expected values are fixed recipes, independent of the large fixture size.
    a = {"XH": "00202600001", "ETL_TIME": OLD}
    b = {"XH": "00202600002", "YDDH": "00000000002", "ETL_TIME": OLD}
    c = {"XH": "00202600003", "ETL_TIME": OLD}
    next_b = {"XH": "00202600002", "ETL_TIME": NEW}
    d = {"XH": "00202600004", "DZXX": "student004@campus.example", "ETL_TIME": "2026-08-05 09:10:00"}
    save("supplemental", "full_row_merge", {"table": CONTACT, "before": [a, b, c], "incoming": [next_b, d]},
        {"rows": [a, next_b, c, d], "added": ["00202600004"], "modified": ["00202600002"], "unchanged": ["00202600001", "00202600003"],
         "database_columns": {"00202600002": {"YDDH": None}}, "raw_absent_keys": {"00202600002": ["YDDH"]}}, "补充假设：合成演变，方案6.1")
    appeared = {**a, "DZXX": "student001@campus.example", "ETL_TIME": NEW}
    save("supplemental", "field_appears", {"table": CONTACT, "before": [a], "incoming": [appeared]},
        {"rows": [appeared], "added": [], "modified": [a["XH"]], "database_columns": {a["XH"]: {"DZXX": "student001@campus.example"}}}, "补充假设：合成演变")
    sparse = {"JGH": "MOCK-SPARSE-001", "ETL_TIME": OLD}
    save("supplemental", "sparse_staff_insert", {"table": STAFF, "rows": [sparse]},
        {"raw_rows": [sparse], "database_columns": {"XM": None, "DWH": None, "DQZTM": None}, "source_valid": True, "staff_query_ready": False},
        "补充假设：仅主键和时间的极稀疏档案", "教职工普通字段非必填；此最小组合不冒充首批十字段实测形状。姓名缺失不能作为业务就绪基准。")
    # SQL NULL is None; String fields store plain text without JSON quotes.
    # These storage oracles are literal constants, not generated by a storage encoder.
    for name, fields, present, value, database_value, basis in (
        ("missing", {}, False, None, None, "实测形状"),
        ("json_null", {"YDDH": None}, True, None, None, "补充边界，未观测"),
        ("empty_string", {"YDDH": ""}, True, "", "", "补充边界，未观测"),
        ("literal_null", {"YDDH": "null"}, True, "null", "null", "实测字符串形态；通讯字段位置为合成假设"),
    ):
        after = {"XH": b["XH"], **fields, "ETL_TIME": NEW}
        save("supplemental", "empty_" + name, {"table": CONTACT, "before": [b], "incoming": [after]},
            {"rows": [after], "field_present": present, "field_value": value,
             "database_columns": {"YDDH": database_value}, "modified": [b["XH"]]}, basis)
    for old, new, old_text, new_text, name in (
        (3, Number("3.0"), "3", "3.0", "integer_decimal"),
        (3, "3", "3", '"3"', "integer_string"),
        (Number("3.0"), "3", "3.0", '"3"', "decimal_string"),
    ):
        before = {"KCH": "000C0001", "XF": old, "ETL_TIME": OLD}
        after = {**before, "XF": new}
        save("supplemental", "numeric_" + name, {"table": COURSE, "before": [before], "incoming": [after]},
            {"rows": [after], "modified": ["000C0001"], "equal": False,
             "database_before": {"KCH": "000C0001", "XF": old_text},
             "database_after": {"KCH": "000C0001", "XF": new_text},
             "schema_change_required": False}, "补充假设：仅数字字面表示/类型变化，方案2.2")
    # Fields AND row order change, numbers retain spelling.
    first = {"KCH": "000C0001", "XF": Number("3.0"), "ETL_TIME": OLD}
    second = {"KCH": "000C0002", "XF": 3, "ETL_TIME": OLD}
    save("supplemental", "reordered", {"table": COURSE, "before": [first, second], "incoming": [dict(reversed(list(second.items()))), dict(reversed(list(first.items())))]},
        {"rows": [first, second], "modified": [], "equal": True}, "补充假设：仅对象字段及记录顺序变化")
    for name, before, after in (
        ("whitespace_only", {**a, "DZXX": " a@campus.example "}, {**a, "DZXX": "a@campus.example"}),
        ("etl_only", a, {**a, "ETL_TIME": NEW}),
    ):
        save("supplemental", name, {"table": CONTACT, "before": [before], "incoming": [after]},
            {"rows": [after], "modified": [a["XH"]]}, "补充假设：单字段变化计修改")
    for name, incoming, before, expected in (
        ("empty_incremental", [], [a, b, c], [a, b, c]),
        ("repeat_incremental", [next_b, d], [a, next_b, c, d], [a, next_b, c, d]),
        ("source_delete_incremental", [], [a, next_b, c, d], [a, next_b, c, d]),
    ):
        save("supplemental", name, {"table": CONTACT, "before": before, "incoming": incoming},
            {"rows": expected, "added": [], "modified": [], "deleted": []}, "补充假设：窗口内无删除标记，未返回行保留")
    save("supplemental", "source_delete_full", {"table": CONTACT, "before": [a, next_b, c, d], "full_snapshot": [a, next_b, d]},
        {"rows": [a, next_b, d], "deleted": [c["XH"]]}, "补充假设：同范围全量可见物理删除")

    boundary_rows = [{"JGH": f"BOUND{i + 1}", "ETL_TIME": time} for i, time in enumerate((
        "2026-08-05 07:59:59", "2026-08-05 08:00:00", "2026-08-05 09:00:00", "2026-08-05 09:59:59", "2026-08-05 10:00:00", "2026-08-05 10:00:01"))]
    save("supplemental", "time_boundaries", {"table": STAFF_CONTACT, "rows": boundary_rows,
        "start_time": "2026-08-05 08:00:00", "end_time": "2026-08-05 10:00:00", "page_size": 2},
        {"primary_keys": ["BOUND2", "BOUND3", "BOUND4"], "page_keys": [["BOUND2", "BOUND3"], ["BOUND4"], []], "total": 3}, "补充假设：本地Asia/Shanghai左闭右开约定")
    equal_time = [{"JGH": f"SAME{i}", "ETL_TIME": NEW} for i in range(1, 5)]
    save("supplemental", "same_time_exact_pages", {"table": STAFF_CONTACT, "rows": equal_time, "page_size": 2,
        "windows": [{"start_time": "2026-08-05", "end_time": "2026-08-06"}, {"start_time": "2026-08-05 08:55:00", "end_time": "2026-08-05 10:00:00"}]},
        {"total": 4, "page_keys": [["SAME1", "SAME2"], ["SAME3", "SAME4"], []], "repeat_modified": [], "overlap_modified": []}, "实测形状：同ETL_TIME多行；边界为模拟约定")

    # Same-person version scenarios are restricted to these three source tables.
    for table in (CONTACT, STAFF_CONTACT, STATUS):
        key = TABLES[table]
        old = deepcopy(baseline[table][0])
        field = "YDDH" if table != STATUS else "XSDQZTM"
        old[field] = "MOCK-OLD"
        newer = {**old, field: "MOCK-NEW", "ETL_TIME": NEW}
        conflict = {**newer, field: "MOCK-CONFLICT"}
        for name, rows, current, expected in (
            ("latest", [newer, old], [], {"rows": [newer]}),
            ("identical_duplicate", [newer, deepcopy(newer)], [], {"rows": [newer]}),
            ("same_time_conflict", [newer, conflict], [], {"error": "same_priority_time_conflict"}),
            ("late_old", [old], [newer], {"rows": [newer], "modified": []}),
            ("cross_batch_conflict", [conflict], [newer], {"error": "same_priority_time_conflict"}),
        ):
            save("supplemental", table + "_" + name, {"table": table, "primary_key": key, "current": current, "incoming": rows, "priority_field": "ETL_TIME"},
                expected, "补充边界：源响应多人次版本；已确认关系：通讯/学籍取最新", "本表字段目录无业务更新时间，使用ETL_TIME；同时间冲突报错。")

    # Business relations: all expected IDs, teacher tokens and transformations are explicit.
    save("supplemental", "latest_term_before_score_filter", {"table": GRADE, "rows": baseline[GRADE][:2],
        "query": {"student_number": "00202600001", "score_min": 90}},
        {"all_grade_ids": ["G000001", "G000002"], "latest_term": {"academic_year": "2026-2027", "semester": "1"}, "filtered_grade_ids": [],
         "derived_numeric_scores": {"G000001": 95, "G000002": Number("70.5")}}, "已采用实测关系：同人同课多ID、多学期；先选最新学期再筛分数")
    save("supplemental", "all_terms_score_filter", {"table": GRADE, "rows": baseline[GRADE][:2],
        "query": {"student_number": "00202600001", "academic_year": "all", "score_min": 90}},
        {"filtered_grade_ids": ["G000001"]}, "接口事实：显式all查询全部学年，sicp-api-design.md第4节")
    members = [
        {"ID": "REL1", "XH": "00202600001", "JHKCH": "000C0001", "JXBH": "J2026-0001", "ETL_TIME": OLD},
        {"ID": "REL2", "XH": "00202600002", "JHKCH": "000C0001", "JXBH": "J2026-0001", "ETL_TIME": OLD}]
    relation_input = {SCHEDULE: baseline[SCHEDULE][:2], MEMBER: members, STAFF: baseline[STAFF][:2], COURSE: baseline[COURSE][:1]}
    save("supplemental", "multiple_schedules_teachers", {"tables": relation_input, "teacher_queries": ["001", "1001", "01"]},
        {"schedule_ids": ["P000001", "P000002"], "teacher_tokens": ["001", "1001"], "teacher_01_matches": [],
         "student_numbers": ["00202600001", "00202600002"], "student_count": 2, "teaching_class_course_count": 1,
         "weekday": 1, "dates": ["2026-09-07"], "sections_by_schedule": {"P000001": [1], "P000002": [2]}, "weeks": [1]}, "已采用实测关系：多个PKH、英文逗号多教师，不做子串匹配")
    duplicate = {**members[0], "ID": "REL3"}
    save("supplemental", "duplicate_members", {"tables": {**relation_input, MEMBER: [*members, duplicate]}},
        {"raw_ids": ["REL1", "REL2", "REL3"], "student_numbers": ["00202600001", "00202600002"], "student_count": 2}, "补充边界：重复成员保留源ID，名单去重")
    term2 = {**baseline[SCHEDULE][0], "PKH": "P-TERM2", "KKXND": "2027-2028"}
    save("supplemental", "cross_term_ambiguity", {"tables": {**relation_input, SCHEDULE: [baseline[SCHEDULE][0], term2]}},
        {"error": "ambiguous_member_term", "source_ids": ["REL1", "REL2"], "choose_term_automatically": False}, "补充边界：同教学班课程跨学期复用")
    for name, token, expected in (("duplicate_teacher_tokens", "001,001,1001", {"teacher_tokens": ["001", "1001"]}),
                                  ("invalid_teacher_separator", "001；1001", {"error": "unsupported_teacher_separator"}),
                                  ("empty_teacher_token", "001,,1001", {"error": "empty_teacher_token"})):
        save("supplemental", name, {"table": SCHEDULE, "rows": [{**baseline[SCHEDULE][0], "JSJGH": token}]}, expected,
            "补充边界：重复/非法分隔未观测；拒绝策略供本地测试，不声明上游规则")
    save("supplemental", "text_score", {"table": GRADE, "rows": [{**baseline[GRADE][0], "KCCJ": "优秀"}]},
        {"raw_KCCJ": "优秀", "numeric_score": None, "business_output_rule": "以只读sicp-api-design.md及实现规则为准"}, "补充边界：未观测文字成绩")
    save("supplemental", "unknown_business_code", {"table": STUDENT,
        "rows": [{**baseline[STUDENT][0], "XBM": "MOCK_UNKNOWN"}]},
        {"raw_XBM": "MOCK_UNKNOWN", "database_columns": {"XBM": "MOCK_UNKNOWN"},
         "code_meaning": None, "schema_change_required": False},
        "补充边界：未观测的业务代码；字符串按原值保存",
        "正常mock采用实测代码样例不等于上游穷尽枚举；未知代码的业务含义不推断。")

    # Full independent variants use one declared source change each.
    def variant(name, alter, expected, note):
        tables = deepcopy(baseline)
        alter(tables)
        save("relation_variants", name, {"tables": tables}, {"source_valid": True, **expected}, "实测缺口变体，方案3及6.1", note)

    def old_class(t):
        t[STATUS][0].update(SZBH="MISSING-OLD-CLASS", SZNJ="2019", RXNY="2019-09-01")
    variant("missing_old_class", old_class, {"student_number": "00202600001", "class_code": "MISSING-OLD-CLASS", "class_name": None}, "历史班级缺档；不推断毕业或删除原因")
    variant("missing_new_class", lambda t: t[STATUS][0].update(SZBH="MISSING-NEW-CLASS"),
        {"student_number": "00202600001", "class_code": "MISSING-NEW-CLASS", "class_name": None}, "新入学在读学生有班号但档案不可用")
    variant("missing_status", lambda t: t[STATUS].pop(0),
        {"student_number": "00202600001", "matched_status": False, "student_query_ready": False, "candidate_publishable": False}, "保留基本档案；不补造学籍，按表规划8.2.1阻止学生就绪")
    for name, missing in (("grade_literal_null_course", "null"), ("grade_missing_old_course", "MISSING-OLD-COURSE")):
        variant(name, lambda t, missing=missing: t[GRADE][0].update(KCH=missing, XN="2021-2022"),
            {"grade_id": "G000001", "raw_course_code": missing, "course_name": None, "preserve_grade": True}, "历史成绩保持源课程号，不猜补课程")
    variant("schedule_missing_course", lambda t: t[COURSE].pop(0),
        {"course_name": None, "course_code": "000C0001", "credits": None, "interface_failure": False,
         "log_contains": {"source_table": SCHEDULE, "primary_key": "P000001", "JHKCH": "000C0001"}}, "JHKCH=KCH等值未匹配，保留排课，关联字段为null并可定位日志")
    variant("member_missing_schedule", lambda t: t[MEMBER][0].update(JXBH="MISSING-TEACHING-CLASS"),
        {"raw_id": "R000001", "matched_schedule": False, "term_determinable": False}, "未匹配排课，不猜测为毕业或无课")
    variant("member_missing_course_key", lambda t: t[MEMBER][0].pop("JHKCH"),
        {"source_valid": False, "document_required_valid": False,
         "raw_id": "R000001", "raw_absent_keys": ["JHKCH"], "member_query_ready": False}, "实测必填字段缺失，仅用于兼容性测试，不属于符合文档的正常数据")
    variant("absent_contact_row", lambda t: t[STAFF_CONTACT].pop(0),
        {"staff_number": "001", "contact_row_present": False, "email": None, "mobile": None}, "区别于存在仅JGH/ETL_TIME的通讯行")
    base_schedule = baseline[SCHEDULE][0]
    always = "PKH JHKCH JSLXM JSSZXQH JXDD KRL SKJC SKJSH SKRQ XDRS XQJ ZC ETL_TIME".split()
    sparse_rows = []
    for size in (8, 10, 11, 12, 13, 20, 21, 22, 25, 26, 27):
        fields = always + [k for k in base_schedule if k not in always and k != "SKSJ"]
        fields = ["PKH", "ETL_TIME"] + [k for k in fields if k not in ("PKH", "ETL_TIME")]
        sparse_rows.append({**{k: base_schedule[k] for k in fields[:size]}, "PKH": f"SPARSE-{size:02d}"})
    save("relation_variants", "schedule_sparse_shapes", {"table": SCHEDULE, "rows": sparse_rows},
        {"source_valid": False, "document_required_valid": False,
         "field_counts": [8, 10, 11, 12, 13, 20, 21, 22, 25, 26, 27], "SKSJ_present": False, "all_rows_business_ready": False},
        "字段数量参考样本；具体字段组合为合成选取", "必填字段缺失，仅用于兼容性测试；不属于符合文档的正常数据")

    # Invalid responses are kept outside source snapshots and have precise failure labels.
    valid = deepcopy(baseline[CONTACT][0])
    missing_pk = {k: v for k, v in valid.items() if k != "XH"}
    for name, body, error in (
        ("missing_primary_key", envelope([missing_pk]), "missing_primary_key"),
        ("array_primary_key", envelope([{**valid, "XH": ["00202600001"]}]), "primary_key_type"),
        ("empty_primary_key", envelope([{**valid, "XH": ""}]), "empty_primary_key"),
        ("null_primary_key", envelope([{**valid, "XH": None}]), "primary_key_type"),
        ("optional_object_type", envelope([{**valid, "YDDH": {"value": "000"}}]), "field_type"),
        ("wrong_list_structure", {"code": 200, "message": "请求成功", "data": {"list": {}, "total": 0}}, "list_not_array"),
        ("missing_data", {"code": 200, "message": "请求成功"}, "missing_data"),
        ("wrong_total_type", {"code": 200, "message": "请求成功", "data": {"list": [], "total": "0"}}, "total_not_integer"),
    ):
        save("invalid_responses", name, {"table": CONTACT, "response": body}, {"error": error, "treat_as_empty": False}, "故意异常，非上游错误码约定")
    save("invalid_responses", "course_duplicate_conflict", {"table": COURSE, "response": envelope([baseline[COURSE][0], {**baseline[COURSE][0], "KCMC": "冲突课程名"}])},
        {"error": "duplicate_primary_key_conflict", "apply_latest_person_rule": False}, "故意异常：课程同号不能套用通讯归并规则")
    # Isolate pagination faults from unrelated required-field failures.
    a, b, c = deepcopy(baseline[CONTACT][:3])
    for name, bodies, error in (
        ("empty_middle_page", [envelope([a], 3), envelope([], 3), envelope([c], 3)], "incomplete_pagination"),
        ("changing_total", [envelope([a], 2), envelope([b], 3)], "inconsistent_total"),
        ("duplicate_across_pages", [envelope([a], 2), envelope([a], 2)], "duplicate_across_pages"),
        ("missing_last_page", [envelope([a], 2)], "incomplete_pagination"),
    ):
        save("invalid_responses", name, {"table": CONTACT, "page_size": 1, "responses": bodies},
            {"error": error, "treat_as_empty": False}, "故意异常：分页完整性")

    # Unknown-field attempts: local column catalog, same request, ordered raw responses.
    for mode in ("full", "incremental"):
        params = {"page": 1, "pageSize": 2}
        if mode == "incremental":
            params.update(startTime="2026-08-05 08:00:00", endTime="2026-08-05 10:00:00")
        normal = {**baseline[STAFF][0], "ETL_TIME": NEW}
        for name, attempts, expected in (
            ("known_column_appears", [envelope([{**normal, "CYM": "虚构曾用名"}])], {"accepted_attempt": 1, "attempts_used": 1, "final_failure_notifications": 0}),
            ("unknown_recovers", [envelope([{**normal, "MOCK_UNKNOWN_FIELD": "test"}]), envelope([normal])], {"accepted_attempt": 2, "attempts_used": 2, "accepted_page_count": 1, "final_failure_notifications": 0}),
            ("unknown_persists", [envelope([{**normal, "MOCK_UNKNOWN_FIELD": "test"}])] * 2, {"error": "unknown_business_field", "attempts_used": 2, "final_failure_notifications": 1}),
            ("unknown_null_persists", [envelope([{**normal, "MOCK_UNKNOWN_FIELD": None}])] * 2, {"error": "unknown_business_field", "attempts_used": 2, "final_failure_notifications": 1}),
        ):
            expected = {**expected, "retry_request_unchanged": True}
            if "error" in expected:
                expected["notification"] = {"recipient": "admin@mock.example", "task": "mock-" + mode, "table": STAFF, "unknown_fields": ["MOCK_UNKNOWN_FIELD"]}
                expected.update(preserve_old_data=True, advance_successful_window=False)
            save("supplemental", mode + "_" + name, {"table": STAFF, "task": "mock-" + mode, "mode": mode,
                "local_business_columns": list(catalog["tables"][STAFF]["fields"]), "request": {"path": "/apizt/openapi/invoke/sjzc/release/" + STAFF, "params": params},
                "max_attempts": 2, "responses": attempts}, expected, "补充假设：未知字段与重试序列，方案6.2", "邮件仅为替身断言，生成器不发送邮件。")
    writer(root / "expected/scenarios.json", index)
