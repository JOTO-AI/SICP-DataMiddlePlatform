import { test, expect } from '@playwright/test'
import { backendCapture } from '../fixtures/backend'

test.beforeEach(async ({ page }) => {
  const fixture = backendCapture('students.grades.query')
  await page.addInitScript(value => {
    window.jsonFixture = value
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (text: string) => { window.jsonCopied = text } } })
  }, { request: JSON.stringify(fixture.request, null, 4) + '\n', response: JSON.stringify(fixture.response) })
  await page.goto('/console/e2e/json.html')
})

test('F02 request editor preserves JSON drafts, failed field edits and loaded backend examples without requests', async ({ page }, testInfo) => {
  const calls: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) calls.push(request.url()) })
  const json = page.getByRole('textbox', { name: '请求 JSON', exact: true })
  const original = await json.inputValue()
  await page.getByRole('button', { name: '参数编辑', exact: true }).click()
  await page.getByRole('button', { name: 'JSON 编辑', exact: true }).click()
  await expect(json).toHaveValue(original)
  await json.fill('{"student_number":')
  await page.getByRole('button', { name: '参数编辑', exact: true }).click()
  await expect(json).toHaveValue('{"student_number":')
  await expect(page.getByRole('alert')).toContainText('原文已保留')
  await page.getByRole('button', { name: '载入参数', exact: true }).click()
  await expect(json).toHaveValue(original)
  await page.getByRole('button', { name: '参数编辑', exact: true }).click()
  const number = page.getByRole('textbox', { name: /^student_number/ })
  await expect(number).toHaveValue('00202600001')
  await number.fill('')
  await page.getByRole('button', { name: '读取编辑稿', exact: true }).click()
  expect(await page.evaluate(() => window.jsonSubmitText)).toBeNull()
  await expect(number).toHaveValue('')
  await expect(number).toHaveAttribute('aria-invalid', 'true')
  await number.fill('00202600001')
  await page.getByRole('button', { name: '读取编辑稿', exact: true }).click()
  expect(JSON.parse((await page.evaluate(() => window.jsonSubmitText))!)).toEqual(backendCapture('students.grades.query').request)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('request-editor-mobile.png') })
  expect(calls).toEqual([])
})

test('F02 response viewer renders bounded backend JSON and copies only visible plain text', async ({ page }, testInfo) => {
  const viewer = page.getByRole('region', { name: '响应内容' })
  const pre = viewer.locator('pre')
  const original = JSON.stringify(backendCapture('students.grades.query').response, null, 2)
  expect(original.length).toBeGreaterThan(4096)
  await expect(viewer.getByRole('button', { name: '格式化 JSON', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(viewer.locator('.tabs button.active')).toHaveCount(1)
  await expect(pre).toHaveText(original.slice(0, 4096))
  await expect(viewer).toContainText('显示已截断')
  await viewer.getByRole('button', { name: '复制当前显示文本', exact: true }).click()
  expect(await page.evaluate(() => window.jsonCopied)).toBe(original.slice(0, 4096))
  await viewer.getByRole('button', { name: '展开内容', exact: false }).click()
  await expect(pre).toHaveText(original.slice(0, 65536))
  await viewer.getByRole('button', { name: '查看原文', exact: true }).click()
  const raw = JSON.stringify(backendCapture('students.grades.query').response)
  await expect(pre).toHaveText(raw.slice(0, 4096))
  await viewer.getByRole('button', { name: '复制当前显示文本', exact: true }).click()
  expect(await page.evaluate(() => window.jsonCopied)).toBe(raw.slice(0, 4096))
  await viewer.getByRole('button', { name: '格式化 JSON', exact: true }).click()
  await expect(pre).toHaveText(original.slice(0, 4096))
  await page.getByRole('button', { name: '验证非 JSON 文本' }).click()
  await expect(pre).toHaveText('<img src=x onerror=alert(1)>')
  await expect(viewer.locator('img')).toHaveCount(0)
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined }))
  await viewer.getByRole('button', { name: '复制当前显示文本', exact: true }).click()
  await expect(viewer.getByRole('textbox', { name: '手动复制响应 JSON' })).toHaveValue('<img src=x onerror=alert(1)>')
  await page.getByRole('button', { name: '恢复后端响应' }).click()
  await expect(viewer.getByRole('textbox')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await pre.scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('response-viewer-mobile.png') })
})
