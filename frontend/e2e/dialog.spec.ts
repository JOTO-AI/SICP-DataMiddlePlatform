import { test, expect } from '@playwright/test'
import { backendCapture } from '../fixtures/backend'
test.beforeEach(async ({ page }) => {
  const fixture = backendCapture('students.query')
  const data = fixture.response.data as { items: Record<string, unknown>[]; synced_at: string }
  await page.addInitScript(value => { window.componentFixture = value }, { rows: data.items, syncedAt: data.synced_at, requestId: fixture.response.request_id! })
  await page.goto('/console/e2e/components.html')
})

test('F02 dialogs teleport, trap focus, nest drawers and restore focus with scroll locks', async ({ page }, testInfo) => {
  const opener = page.getByRole('button', { name: '打开弹窗', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: '组件弹窗', exact: true })
  await expect(dialog).toBeVisible()
  expect(await dialog.evaluate(element => element.parentElement?.tagName)).toBe('BODY')
  expect(await page.evaluate(() => document.documentElement.style.overflow)).toBe('hidden')
  await dialog.getByRole('button', { name: '关闭弹窗', exact: true }).focus()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: '完成查看' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: '关闭弹窗', exact: true })).toBeFocused()
  await dialog.getByRole('button', { name: '打开抽屉' }).click()
  const drawer = page.getByRole('dialog', { name: '记录详情', exact: true })
  await expect(drawer).toBeVisible()
  await expect(page.locator('dialog[open]')).toHaveCount(2)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await drawer.evaluate(element => ({ width: element.getBoundingClientRect().width, top: element.getBoundingClientRect().top, height: element.getBoundingClientRect().height }))).toEqual({ width: 390, top: 0, height: 844 })
  expect(await drawer.locator('.dialog-body').evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('drawer-mobile.png'), fullPage: false })
  await page.keyboard.press('Escape')
  await expect(drawer).not.toBeVisible()
  await expect(dialog.getByRole('button', { name: '打开抽屉' })).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.style.overflow)).toBe('hidden')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(opener).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.style.overflow)).toBe('')
  expect(await page.evaluate(() => window.componentEvents)).toEqual(['drawer:escape', 'dialog:escape'])
})

test('F02 ordinary dismiss and stopping asynchronous wait emit one close event', async ({ page }, testInfo) => {
  await page.getByRole('button', { name: '打开弹窗', exact: true }).click()
  await page.getByRole('dialog', { name: '组件弹窗' }).waitFor()
  await page.mouse.click(2, 2)
  await expect(page.getByRole('dialog', { name: '组件弹窗' })).not.toBeVisible()
  expect(await page.evaluate(() => window.componentEvents)).toEqual(['dialog:backdrop'])
  const opener = page.getByRole('button', { name: '打开异步弹窗' })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: '确认异步操作' })
  await dialog.getByRole('button', { name: '确认提交', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '正在等待…', exact: true })).toBeDisabled()
  await expect(dialog.getByRole('status')).toContainText('不会取消已提交的后台操作')
  await page.screenshot({ path: testInfo.outputPath('async-wait.png'), fullPage: false })
  await dialog.getByRole('button', { name: '停止等待', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(opener).toBeFocused()
  await expect(page.getByText('已停止等待，受理结果仍待确认。')).toBeVisible()
  expect(await page.evaluate(() => window.componentEvents)).toEqual(['dialog:backdrop', 'confirm', 'action:dismiss'])
})
